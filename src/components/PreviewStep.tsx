import type { Counts } from "../lib/commits";
import { iso } from "../lib/dates";
import { downloadSvg } from "../lib/download";
import { renderHeatmap } from "../lib/heatmapSvg";
import { PALETTES, type Palette, type PaletteKey } from "../lib/palettes";

type Props = { counts: Counts; hasText: boolean; palette: Palette; paletteKey: PaletteKey; caption: string };

export default function PreviewStep({ counts, hasText, palette, paletteKey, caption }: Props) {
  const rendered = counts.size ? renderHeatmap(counts, palette, caption) : null;

  const downloadOne = () => rendered && downloadSvg(`commit-heatmap-${paletteKey}.svg`, rendered.svg);
  const downloadBoth = () => {
    if (!rendered) return;
    downloadSvg("commit-heatmap-light.svg", renderHeatmap(counts, PALETTES.light, caption).svg);
    setTimeout(() => downloadSvg("commit-heatmap-dark.svg", renderHeatmap(counts, PALETTES.dark, caption).svg), 300);
  };

  return (
    <section className="card">
      <div className="row" style={{ justifyContent: "space-between" }}>
        <h2 style={{ margin: 0 }}>4. Preview and download</h2>
        <div className="row">
          <button type="button" className="primary" onClick={downloadOne}>
            Download SVG
          </button>
          <button type="button" onClick={downloadBoth}>
            Download light + dark
          </button>
        </div>
      </div>
      <p className="status" role="status">
        {rendered ? (
          `${rendered.total.toLocaleString("en-US")} commits on ${rendered.days.toLocaleString("en-US")} days, ${iso(rendered.start)} to ${iso(rendered.end)}`
        ) : hasText ? (
          <span className="err">No "count YYYY-MM-DD" lines found.</span>
        ) : (
          "Paste your counts or try the sample data."
        )}
      </p>
      {/* the SVG is generated by renderHeatmap, which escapes the only user text (the caption) */}
      <div className="preview" dangerouslySetInnerHTML={{ __html: rendered?.svg ?? "" }} />
      <details style={{ marginTop: 12 }}>
        <summary>Show both themes on your GitHub profile README</summary>
        <pre>{`<picture>
  <source media="(prefers-color-scheme: dark)" srcset="commit-heatmap-dark.svg">
  <img alt="Commit heatmap" src="commit-heatmap-light.svg">
</picture>`}</pre>
      </details>
    </section>
  );
}
